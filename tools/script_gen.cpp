// Recording scripts for Step 1b (D-52). Balanced, seeded, same result every time.
//   script_gen data/phraseology/placeholder.json data/phraseology/negatives.txt --speaker d1 [--seed N] [--out FILE]
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <map>

#include "phraseology/ScriptGen.h"
using namespace atc;

int main(int argc, char** argv) {
  if (argc < 3) {
    std::fprintf(stderr, "usage: script_gen PHRASEOLOGY.json NEGATIVES.txt --speaker ID [--seed N] [--out FILE]\n");
    return 2;
  }
  Phraseology p;
  std::string error, speaker, outFile;
  ScriptOptions o;
  if (!loadPhraseology(argv[1], p, error)) return std::fprintf(stderr, "%s\n", error.c_str()), 1;
  std::ifstream nf(argv[2]);
  for (std::string l; std::getline(nf, l);) {
    const auto bar = l.find('|');
    if (l.empty() || l[0] == '#' || bar == std::string::npos) continue;
    const auto trim = [](std::string s) {
      s.erase(0, s.find_first_not_of(' '));
      s.erase(s.find_last_not_of(" \r") + 1);
      return s;
    };
    o.negativeTexts.emplace_back(trim(l.substr(0, bar)), trim(l.substr(bar + 1)));
  }
  for (int i = 3; i + 1 < argc; i += 2) {
    const std::string k = argv[i], v = argv[i + 1];
    if (k == "--speaker") speaker = v;
    else if (k == "--seed") o.seed = static_cast<std::uint32_t>(std::atoi(v.c_str()));
    else if (k == "--out") outFile = v;
    else return std::fprintf(stderr, "bad option %s\n", k.c_str()), 2;
  }
  if (speaker.empty()) return std::fprintf(stderr, "need --speaker\n"), 2;
  const auto script = makeScript(p, o, error);
  if (script.empty()) return std::fprintf(stderr, "%s\n", error.c_str()), 1;
  std::string text = "# Speaker " + speaker + ", seed " + std::to_string(o.seed) + ". " +
                     (p.validated ? "" : "PLACEHOLDER - NOT APPROVED PHRASEOLOGY. ") + "Generated by script_gen; do not edit.\n";
  for (const auto& x : script) text += phraseLine(x) + "\n";
  if (outFile.empty()) std::fputs(text.c_str(), stdout);
  else if (!(std::ofstream(outFile) << text)) return std::fprintf(stderr, "cannot write %s\n", outFile.c_str()), 1;
  std::map<std::string, int> tags;
  int neg = 0;
  for (const auto& x : script) {
    neg += x.negative;
    for (const auto& t : x.tags) ++tags[t];
  }
  std::fprintf(stderr, "%zu phrases, %d negative\n", script.size(), neg);
  for (const auto& [k, n] : tags) std::fprintf(stderr, "  %-18s %d\n", k.c_str(), n);
  return 0;
}
